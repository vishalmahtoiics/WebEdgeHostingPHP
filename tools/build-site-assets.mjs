// Builds the small CSS + icon font used by the public website (home, services, blog).
// Run after changing views/site/*, views/layouts/site.php or public/assets/css/site.css:
//   npm i purgecss@6 && pip install fonttools brotli
//   node tools/build-site-assets.mjs
// Output: public/assets/css/site.bundle.css and public/assets/fonts/site-icons.woff2
import { PurgeCSS } from 'purgecss';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (f) => join(root, f);
const content = [
    ...readdirSync(p('views/site')).map((f) => p('views/site/' + f)),
    p('views/layouts/site.php'),
    p('public/assets/js/site.js'),
];

// 1. Bootstrap: keep only what the public pages use (plus classes Bootstrap's JS adds).
const [boot] = await new PurgeCSS().purge({
    content,
    css: [p('public/assets/vendor/bootstrap/bootstrap.min.css')],
    variables: true,
    safelist: {
        standard: ['show', 'showing', 'collapsing', 'collapse', 'active', 'disabled', 'fade', 'in', 'scrolled', 'was-validated'],
        deep: [/^navbar/, /^dropdown/, /^collapse/, /^alert/, /^col-/, /^g-/, /^offset-/, /^order-/, /^table/],
        greedy: [/data-bs-popper/],
    },
});

// 2. Icons: every icon name that appears in the public views, the service icon list and JS.
const icons = readFileSync(p('public/assets/vendor/bootstrap-icons/bootstrap-icons.min.css'), 'utf8');
const all = new Map([...icons.matchAll(/\.bi-([a-z0-9-]+)::before\{content:"\\([0-9a-f]+)"\}/g)].map((m) => [m[1], m[2]]));
const sources = [...content, p('app/Support/SiteServices.php'), p('app/Support/Seo.php')].map((f) => readFileSync(f, 'utf8')).join('\n');
const used = new Set();
for (const m of sources.matchAll(/bi-([a-z0-9-]+)/g)) if (all.has(m[1])) used.add(m[1]);
for (const m of sources.matchAll(/'([a-z0-9-]+)'/g)) if (all.has(m[1])) used.add(m[1]);
const names = [...used].sort();
const codes = names.map((n) => 'U+' + all.get(n).toUpperCase());
execFileSync('pyftsubset', [p('public/assets/vendor/bootstrap-icons/fonts/bootstrap-icons.woff2'), '--unicodes=' + codes.join(','), '--flavor=woff2', '--output-file=' + p('public/assets/fonts/site-icons.woff2'), '--no-hinting', '--desubroutinize']);
const iconCss = '@font-face{font-display:block;font-family:"bootstrap-icons";src:url("../fonts/site-icons.woff2") format("woff2")}'
    + '.bi::before,[class^="bi-"]::before,[class*=" bi-"]::before{display:inline-block;font-family:bootstrap-icons!important;font-style:normal;font-weight:400!important;font-variant:normal;text-transform:none;line-height:1;vertical-align:-.125em;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}'
    + names.map((n) => `.bi-${n}::before{content:"\\${all.get(n)}"}`).join('');

const site = readFileSync(p('public/assets/css/site.css'), 'utf8');
writeFileSync(p('public/assets/css/site.bundle.css'), '/* Generated by tools/build-site-assets.mjs — do not edit; edit site.css and rebuild. */\n' + boot.css + '\n' + iconCss + '\n' + site);
console.log(`site.bundle.css: ${Math.round((boot.css.length + iconCss.length + site.length) / 1024)} KB, ${names.length} icons`);
