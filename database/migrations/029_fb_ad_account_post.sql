## First, find out what exactly is restricted

Meta can restrict different things, and the fix depends on which one it is. Open **Account Quality** (in Meta Business Suite, or at facebook.com/accountquality) while logged in. It lists everything that has a problem:

- **Ad account disabled** – only that ad account cannot run ads. Other ad accounts may still work.
- **Profile restricted from advertising** – your personal Facebook profile cannot create or manage ads in any account. This is more serious.
- **Business portfolio (Business Manager) restricted** – the whole business portfolio and its ad accounts are affected.
- **Page restricted** – the Facebook Page linked to the ads has a problem of its own.
- **Payment issue** – ads stopped because a payment failed or there is an unpaid balance.

