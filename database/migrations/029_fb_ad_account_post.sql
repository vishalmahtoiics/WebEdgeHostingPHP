## Why ad accounts get disabled

Meta rarely gives a detailed reason, but in practice it is almost always one of these:

1. **Suspicious login or hacked account.** A login from a new country, a VPN, or a hacker using your account to run ads. Meta disables first to protect you.
2. **Payment problems.** A failed card or UPI payment, a card that is used on many ad accounts, or an unpaid balance. Prepaid and auto-pay failures are common in India.
3. **Policy violations in ads.** Restricted topics such as loans and credit, crypto, health "cures", before-and-after weight-loss photos, adult content, or exaggerated income claims ("earn ₹50,000 a week").
4. **Misleading landing pages.** The website does not match the ad, has no contact details or privacy policy, or looks like a scam.
5. **Circumventing systems.** Creating new ad accounts or profiles after a ban, using someone else''s account to run blocked ads, or cloaking landing pages. This is treated very seriously.
6. **New account spending too fast.** A brand-new account suddenly spending large amounts can look like fraud.

## Step 1: Secure your Facebook account first

If there is any chance the account was hacked, fix that before appealing:

- Change your Facebook password and turn on **two-factor authentication**.
- Check **Where you''re logged in** and log out of devices you do not know.
- In Business settings, check **People** and **Partners** and remove anyone you do not recognise.
- Check Ads Manager for campaigns you did not create, and your payment methods for unknown charges. Contact your bank if your card was misused.

Meta often asks you to secure the account as part of the review, and an appeal from a still-compromised account is unlikely to succeed.

## Step 2: Fix the problem behind the restriction

Before you click "Request review", remove the likely cause:

- **Payments:** clear any unpaid balance, remove cards you no longer use, and add a valid payment method in your own business name.
- **Ads:** pause or edit ads that touch restricted topics or make unrealistic claims. Read Meta''s Advertising Standards for your industry.
- **Landing page:** make sure your website loads fast, matches the ad, and shows your business name, address, phone number, privacy policy and terms. Our [business website checklist](/blog/business-website-design-checklist) covers what a trustworthy site needs.
- **Business details:** complete your business portfolio information and verify your business if Meta offers it.

## Step 3: Request a review in Account Quality

1. Open **Account Quality** and select the restricted asset (ad account, profile or business portfolio).
2. Click **Request review** and follow the steps. Meta may ask you to confirm your identity with a code, a selfie video or an ID document.
3. Explain briefly and honestly what happened and what you have changed, for example: "Our account was accessed from an unknown device and ads were created without our permission. We have changed the password, turned on two-factor authentication and removed the unknown user."

Request a review **once** for each restriction and wait for the result. Repeated requests do not speed things up. Reviews usually take from a day to a couple of weeks.

If you have **Meta Verified for business**, you can also contact Meta''s support team through it for help with a disabled account.

## Step 4: What not to do while you wait

These mistakes turn a temporary problem into a permanent one:

- **Do not create a new ad account, profile or business portfolio to keep advertising.** Meta treats this as circumventing its systems and can permanently ban everything linked to you.
- **Do not run ads through a friend''s or agency''s account** to get around the restriction.
- **Do not buy "aged" ad accounts or pay "unban services".** They break Meta''s terms, and many are scams.
- **Do not keep changing payment cards** across several ad accounts.

## Step 5: If the appeal is rejected

If Meta keeps the restriction after review, the decision is often final for that asset. You can:

- Check whether **other ad accounts** in your business portfolio are still allowed to advertise.
- Keep growing through channels you control: your website, Google Business Profile, WhatsApp and **Google Ads**. Our guide to [Google Ads vs Facebook Ads](/blog/google-ads-vs-facebook-ads) helps you decide where to put your budget.

