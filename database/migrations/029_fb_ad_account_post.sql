## Frequently asked questions

### Why was my Facebook ad account disabled without any reason?

Meta''s systems usually disable ad accounts automatically when they detect suspicious logins, payment problems or ads that may break the Advertising Standards. Open Account Quality to see which asset is restricted, then fix the likely cause and request a review.

### How long does a Facebook ad account review take?

Most reviews are completed within a few days, but some take up to a couple of weeks. Request a review only once per restriction; repeated requests do not make it faster.

### Can I create a new ad account if my Facebook ad account is disabled?

You should not. Creating new accounts or profiles to keep advertising after a restriction is treated as circumventing Meta''s systems and can lead to a permanent ban on everything linked to you.

### What is the difference between a disabled ad account and a profile restricted from advertising?

A disabled ad account affects only that account. A profile restricted from advertising means your personal Facebook profile cannot create or manage ads anywhere, which affects every ad account you work in.

### How can I avoid my Facebook ad account being disabled?

Secure every admin with two-factor authentication, use one valid payment method, avoid VPN logins, follow the rules for restricted topics, send ads to a clear and honest landing page, and increase budgets on new accounts gradually.

