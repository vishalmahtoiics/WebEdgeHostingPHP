## Why WhatsApp bans business numbers

WhatsApp rarely tells you the exact reason, but almost every ban we see comes from one of these:

1. **Unofficial apps.** GB WhatsApp, WhatsApp Plus, FM WhatsApp and similar "modded" apps break WhatsApp''s terms. Many temporary bans start here, and repeat use leads to permanent bans.
2. **Bulk messaging tools and auto-senders.** Chrome extensions or software that send hundreds of messages from the normal app are one of the biggest causes of bans for Indian businesses.
3. **Messaging people who did not ask to hear from you.** Bought number lists, contacts collected from groups, or sending offers to people who never contacted you.
4. **Many users blocking or reporting you.** Even if your messages are genuine, if many people block your number in a short time, WhatsApp treats it as spam.
5. **Adding people to groups without permission,** or creating many groups quickly.
6. **Sending the same message to many chats at once,** especially with links, and especially from a new number.
7. **Selling restricted products or services** that are not allowed under WhatsApp''s Commerce Policy.
8. **Sharing misleading, harmful or illegal content,** including fake offers or impersonating another brand.

Notice that most of these come down to one idea: WhatsApp protects users from unwanted messages. A number that behaves like a spammer gets banned, even if the business behind it is honest.

## Step 1: Stop doing anything that caused the ban

Before you appeal:

- **Uninstall any unofficial WhatsApp app** and install the official WhatsApp Business app from the Google Play Store or Apple App Store.
- **Turn off bulk senders, auto-reply extensions and any third-party tool** connected to your WhatsApp.
- **Do not keep registering the same number again and again.** Repeated attempts can make things worse.
- **Do not buy "ban removal" services.** Nobody outside WhatsApp can remove a ban, and some of these services simply take your money – or ask for your OTP, which is how accounts get stolen.

If you have a temporary ban, wait for the timer to finish, then log in again using only the official app. When WhatsApp asks you to move your chats from the unofficial app, follow the steps shown and back up first.

## Step 2: Request a review from inside the app

For a permanent ban, the fastest route is the **Request a review** option that appears on the ban screen when you try to register your number:

1. Open the official WhatsApp Business app and enter your banned number.
2. When the ban message appears, tap **Support** or **Request a review**.
3. Verify the number with the OTP.
4. Write a short, honest explanation and submit.

Keep the explanation polite and factual. For example:

"This number belongs to Sharma Electronics, a registered shop in Indore, and is used to reply to customer enquiries and send order updates to customers who contact us. We had used a bulk messaging extension and have now removed it. We will only message customers who contact us first or have agreed to receive updates. Please review our account."

If you broke a rule, say so and say what you changed. Reviews that admit the mistake and show a clear fix tend to do better than reviews that claim "we did nothing wrong".

## Step 3: Contact WhatsApp support if there is no review button

If you do not see the review option, contact WhatsApp support through the **Contact us** form on the WhatsApp Help Center, choosing the option for a banned account. Include:

- Your phone number in full international format, for example +91 98XXX XXXXX
- Your business name and what your business does
- The screenshot of the ban message
- What happened before the ban and what you have changed

Use one clear request rather than many repeated ones. Reviews can take from a few hours to several days, and WhatsApp''s decision after review is usually final.

## What to do while your number is banned

A ban can cut off your customers overnight, so protect your business while you wait:

- **Tell customers through other channels.** Post on Instagram, Facebook and your Google Business Profile that they can reach you on your call number, email or a temporary WhatsApp number.
- **Put your contact details on your website,** with a call button and a contact form, so enquiries do not stop. A fast, mobile-friendly site is your best backup – see our [business website design checklist](/blog/business-website-design-checklist).
- **Use a separate number for the temporary account** and follow the rules strictly from day one. Do not use the new number to bulk message your old contact list.
- **Keep a record of customer details** outside WhatsApp. If your whole order history lives only inside chats, a ban means losing it.

## If the ban is final

If WhatsApp rejects the review, the number cannot be used on WhatsApp again. Start fresh with a new number, but do it properly:

- Register the new number on the official WhatsApp Business app and complete your business profile – name, category, address, hours and website.
- Share the new number on your website, Google Business Profile, invoices and social media.
- Let customers message you first using a click-to-chat link or QR code, instead of sending messages to your old contact list.
- Build up slowly. A new number that suddenly sends hundreds of messages is very likely to be banned again.

