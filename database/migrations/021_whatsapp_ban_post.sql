## Temporary ban or permanent ban – know which one you have

WhatsApp shows different messages, and the right next step depends on which one you see:

- **Temporary ban with a countdown timer.** Usually caused by using an unofficial version of WhatsApp or by sudden spam-like activity. The number is blocked for a fixed time, and the ban lifts on its own when the timer ends.
- **"This account is not allowed to use WhatsApp" (permanent ban).** WhatsApp believes the number broke its Terms of Service. You need to request a review to get it back.
