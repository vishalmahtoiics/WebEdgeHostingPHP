## Frequently asked questions

### Why was my WhatsApp Business account banned without warning?

WhatsApp''s systems automatically ban numbers that look like spam, for example numbers using unofficial apps or bulk senders, messaging many people who never contacted them, or being blocked and reported by many users in a short time. They usually do not tell you the exact reason.

### How long does a temporary WhatsApp ban last?

A temporary ban shows a countdown timer in the app, and it lifts automatically when the timer ends. Switch to the official WhatsApp Business app before logging in again, because continuing to use an unofficial app can lead to a permanent ban.

### Can a permanently banned WhatsApp number be unbanned?

Sometimes. If you request a review and WhatsApp agrees the ban was a mistake or that you have fixed the problem, it can restore the number. If the review is rejected, the decision is usually final and you need to use a new number.

### Will I get my chats back after the ban is lifted?

If your account is restored on the same phone, your chats are usually still there. If you reinstall or change phones, you can only restore chats from a backup on Google Drive or iCloud, so keep backups switched on.

### Is it safe to use bulk WhatsApp sender software?

No. Bulk sender tools that work through the normal WhatsApp or WhatsApp Business app break WhatsApp''s terms and are one of the most common reasons business numbers get banned. For high volumes, use the official WhatsApp Business Platform through an approved provider.

