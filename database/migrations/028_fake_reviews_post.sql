## Frequently asked questions

### Can I delete a Google review myself?

No. Business owners cannot delete reviews. You can report a review that breaks Google''s policies, and Google decides whether to remove it. You can also reply publicly to any review.

### How long does Google take to remove fake Google reviews?

Google usually checks reported reviews within a few days. You can follow the status, and appeal if needed, in the Google Business Profile reviews management tool. Large review attacks can take longer.

### Will Google remove a negative review that is genuine?

Usually not. Google keeps genuine customer opinions even if they are negative or harsh, unless they break a specific policy such as harassment, off-topic content or personal information.

### Can a competitor be stopped from posting fake reviews?

Reviews from competitors break Google''s conflict of interest policy and can be reported for removal. If the attacks continue or include threats, keep evidence and consider a police complaint or legal advice.

### Is it okay to ask customers for reviews?

Yes. Asking genuine customers for honest reviews is allowed and encouraged. Offering money, discounts or gifts in exchange for reviews, or asking only happy customers in a way that filters out others, is not allowed.

