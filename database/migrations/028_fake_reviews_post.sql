## Which reviews can Google actually remove?

Google does **not** remove a review just because it is negative or unfair. It removes reviews that break its **prohibited and restricted content** policy. The ones that matter most for businesses:

- **Spam and fake engagement** – reviews from people who were never customers, bulk reviews from the same person or group, reviews posted by bots or paid reviewers.
- **Conflict of interest** – reviews left by competitors, current or former employees, or anyone reviewing a business they are connected to.
- **Off-topic content** – reviews about politics, personal arguments or a different business, not about the customer''s experience.
- **Offensive, hateful or harassing content** – abuse, threats, slurs or bullying of named staff.
- **Personal information** – phone numbers, addresses or private details of you or your staff.
- **Impersonation** – someone pretending to be another person or business.

If a review is genuine but harsh, Google will usually keep it. In that case your reply matters more than removal (see Step 4).

## Step 1: Collect evidence before you do anything

Before you report, build a simple record:

- **Screenshots** of each review with the reviewer''s name, date and star rating.
- **Your customer records** – billing software, appointment book, delivery records – showing there is no customer with that name or on that date.
- **Patterns** – many reviews within a few hours, similar wording, new profiles with no photo and only one review, or reviewers who also praised a competitor nearby.
- **Any threats or demands**, such as messages asking for money to remove reviews. Keep these – they can also be reported to the police.

This evidence helps when you appeal, and if you ever need to take legal action.

## Step 2: Report each fake review from your Business Profile

Report from the account that manages the profile:

1. Search your business name on Google or open the Google Maps app while signed in, and open your profile''s **Reviews**.
2. Next to the review, tap the three dots and choose **Report review**.
3. Choose the reason that **matches the policy** – for example "Conflict of interest" for a competitor or ex-employee, "Spam" for fake or bulk reviews, "Off topic" or "Profanity/harassment" where it fits.
4. Repeat for each review individually.

Choosing the right reason matters. "This review is unfair" is not a policy reason; "this person was never a customer and posted 15 reviews in one hour" is spam.

## Step 3: Track the report and appeal if needed

Google''s **Reviews Management Tool** (search for "Google Business Profile reviews management tool") lets you:

- See the **status** of each review you reported.
- **Appeal** a decision if Google decided not to remove a review that you still believe breaks the policy. Use the appeal to explain the evidence clearly and briefly.

Reviews are usually checked within a few days. If you are facing a sudden flood of fake reviews (a "review attack"), report them and also contact Google Business Profile support through the Help Center. Google sometimes protects a profile during unusual review activity.

## Step 4: Reply to every fake review – calmly

While Google reviews your report, future customers are reading those reviews. A calm public reply protects your reputation better than silence:

> "Hello, we could not find any visit or order under this name in our records for this date. We take every customer''s experience seriously – please call us on our number so we can look into it. – Team Sharma Dental"

Rules for replying:

- **Never argue, insult or threaten** the reviewer – other customers will judge your reply, not the review.
- **Never share personal details** of a real customer in your reply.
- **Keep it short and factual**, and invite them to contact you offline.

If the review is later removed, your reply disappears with it. If it stays, your reply shows readers that the review is doubtful.

## Step 5: If it is defamation or extortion

Some cases go beyond Google''s tools:

- **Extortion:** someone demands money to remove reviews or threatens to post more. Do not pay. Keep all messages and report it at **cybercrime.gov.in** or to your local police.
- **Serious false statements:** reviews that falsely accuse you of crimes or seriously harm your reputation may be defamation. Speak to a lawyer – Google can act on a valid court order.

## Step 6: Rebuild your rating the right way

The best long-term protection against fake reviews is a steady stream of **genuine** ones. A profile with 300 real reviews barely moves when a few fake ones appear.

- **Ask every happy customer** for a review – at the counter, on the invoice, in a WhatsApp message after delivery, or with a QR code at the reception.
- **Use your short review link** from your Business Profile ("Ask for reviews") so customers reach the review box in one tap.
- **Reply to every review**, good and bad. It shows you care and encourages more people to review.
- **Never buy reviews or offer discounts in exchange for reviews.** It breaks Google''s policies and can get your own reviews removed or your profile restricted. Our guide on [Google Business Profile suspension](/blog/google-business-profile-suspended-fix) explains what happens when profiles break the rules.

