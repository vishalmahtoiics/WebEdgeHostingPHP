## Why was my Instagram account hacked?

Knowing how it happened helps you close the door afterwards. When a business finds its Instagram account hacked, it is almost always one of these:

- **Fake "copyright" or "verification" messages** in DMs or email that link to a page asking you to log in. These look like Meta but are not.
- **Someone asking for an OTP or code** – "I sent you a code by mistake, please send it back". That code was your password reset code.
- **Reused passwords.** The same password used on another website that was leaked.
- **Old agencies, freelancers or employees** who still have the password or access through Meta Business Suite.
- **Third-party apps** for followers, likes or scheduling that were given access to the account.

## Step 1: Check your email inbox first – right now

When someone changes the email address on your account, Instagram sends a message to the **old** email address. That message usually has a link like **"revert this change"** or **"secure your account"**.

1. Search your email for messages from Instagram sent in the last few days, including the spam folder.
2. Open the one about an email or phone change and use the link to undo it and reset the password.
3. Do this as early as possible – these links stop working after some time.

Be careful: hackers also send fake "Instagram" emails. Only trust links from messages you can match in the app under **Settings → Accounts Center → Password and security → Emails from Instagram** (once you are back in), and never enter your password on a page you reached from a DM.

## Step 2: Use Instagram''s official recovery page

If the email link did not work, use Instagram''s own recovery flow:

1. Open the Instagram app (not a browser on a shared computer), tap **Forgot password?** or **Get help logging in**, and enter your username, email or phone number.
2. If you no longer have access to the email or phone on the account, choose the option for help with **my account was hacked** or **I can''t access this email or phone number**. You can also start at **instagram.com/hacked**.
3. Instagram may send a security code to an email address or phone number you provide. Use an email that the hacker does not know.

Use the device and Wi-Fi network you normally use for Instagram. Instagram recognises familiar devices, which makes recovery more likely.

## Step 3: Verify your identity

For many hacked accounts, Instagram asks you to prove the account is yours:

- **Video selfie verification:** if the account has photos of you, you may be asked to record a short video turning your head in different directions. Instagram compares it with photos on the profile. The video is used for verification only.
- **Business details:** for brand accounts without your face, Instagram may ask for information such as the email or phone number used to create the account, or the type of device you used.

Answer exactly and honestly. Reviews usually take from a few days to a couple of weeks. Do not submit many requests at once – it can slow things down.

If you subscribe to **Meta Verified**, you can also use its account support to contact a person at Meta about the hacked account.

## Step 4: Warn your customers and followers

While you work on recovery, the hacker may still be posting or messaging people from your account. Protect your customers and your reputation:

- Post a short message on your **other channels** – Facebook, WhatsApp status, Google Business Profile and website – saying the Instagram account was hacked and asking people **not to send money or click links** from it.
- Ask friends and loyal followers to **report the account** as hacked from inside the app. This can speed up action from Instagram.
- If customers paid money to the hacker, advise them to report it at **cybercrime.gov.in** or call the **1930** cyber fraud helpline as quickly as possible.

## Step 5: Once you are back in – lock it down

Getting the password back is only half the job. Before you do anything else:

1. **Change the password** to a new, long one you have never used anywhere else.
2. **Turn on two-factor authentication** in **Accounts Center → Password and security → Two-factor authentication**. Use an authenticator app rather than SMS if you can.
3. **Check the email address and phone number** on the account and remove anything the hacker added.
4. **Log out unknown devices** under **Where you''re logged in**.
5. **Remove apps and websites** you do not recognise from the account''s connected apps.
6. **Check posts, stories, highlights, bio link and DMs** for anything the hacker added, and delete it.
7. **Download your data** (Accounts Center → Your information and permissions) so you have a backup of photos and posts.

## Step 6: Check Facebook, ads and Meta Business Suite

Hackers often target business accounts because of the **linked ad account**. Check these immediately:

- **Meta Business Suite / Business Manager → People and Partners:** remove anyone you do not recognise, especially new admins.
- **Ads Manager:** pause or delete ads you did not create, and check the **billing and payment methods** for unknown charges. Contact your bank if your card was used.
- **Linked Facebook Page:** check page roles and recent posts.

If unknown ads were run on your card, report it through Meta''s ads support and keep screenshots of the charges.

