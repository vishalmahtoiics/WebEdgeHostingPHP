- Keep trying the official flow from your usual device for a few weeks – some accounts are recovered late.
- Create a **new account** with a slightly different handle, verify it with your website and other channels, and tell customers about the change.
- Ask Instagram to remove the hacked account if it is being used to scam people, by reporting it as impersonating your business.

