## Frequently asked questions

### What should I do first if my Instagram account is hacked?

Check the email inbox linked to the account for a message from Instagram about an email or password change, and use its link to revert the change. If that is not possible, start the official recovery from the Instagram app using Forgot password or Get help logging in.

### How long does it take to recover a hacked Instagram account?

If you can use the email link, often within minutes. If you need identity verification, it usually takes a few days to a couple of weeks, depending on how quickly Instagram reviews your request.

### Can I recover my Instagram account if the hacker changed my email and phone number?

Often yes. Use the option for a hacked account or for when you cannot access your email or phone, and complete the identity verification, such as a video selfie or details about how the account was created.

### Should I pay someone who promises to recover my Instagram account?

No. People who offer paid recovery on Instagram, Telegram or websites are very often scammers, and some ask for your new login details. Use only Instagram''s official tools and Meta Verified support.

### How can I protect my business Instagram account?

Use a unique password, turn on two-factor authentication, never share login codes, give your team and agencies access through Meta Business Suite instead of the password, and regularly remove unknown devices and apps.

