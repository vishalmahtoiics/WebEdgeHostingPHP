## What "business profile suspended" actually means

Google uses a few different states, and it helps to know which one you are in:

- **Suspended (not verified):** the profile may still appear on Maps, but you lose the ability to manage it, reply to reviews or see insights. Often caused by a risky edit or a guideline issue.
- **Disabled or removed:** the profile no longer appears on Google Search or Maps at all. This is the serious one.
- **Limited or restricted features:** for example, you cannot get new reviews or edit some fields for a while. This is not a full suspension.

Open your profile from the Google account that manages it (search your business name on Google while signed in, or go to business.google.com). The message at the top tells you which state you are in. Take a screenshot – you will need it.

## The most common reasons for a suspension

Google rarely tells you the exact reason, but in practice almost every suspension comes from one of these:

1. **Extra words in the business name.** "Sharma Dental Clinic – Best Dentist in Pune Root Canal Implants" is keyword stuffing. Your name on Google must match the name on your signboard, letterhead and documents – nothing more.
2. **An address that does not qualify.** Virtual offices, co-working desks you do not staff, PO boxes and a friend''s address are not allowed. Google wants a place where you actually meet customers, or a service area if you go to them.
3. **Service-area business showing a home address.** If you visit customers (plumbers, electricians, pest control, home tutors), you should hide your address and set service areas instead.
4. **Too many changes at once.** Changing name, category, address and phone number together – or very often – looks like a takeover to Google''s systems.
5. **Duplicate profiles** for the same business at the same address.
6. **Fake or paid reviews,** review exchanges, or offering discounts in return for reviews.
7. **Restricted or high-risk categories,** such as locksmiths, packers and movers, certain financial services, or "customer care" style listings, which are checked more strictly.
8. **Mismatch between your listing and your website,** such as a different phone number or address on the site.

## Step 1: Do not panic-edit or create a new profile

This is the most important step, and the one most people get wrong.

- **Do not create a new profile** for the same business. Google treats it as an attempt to get around the suspension, and it can make reinstatement much harder.
- **Do not keep changing details** while the profile is suspended. Every change can reset or confuse the review.
- **Do not pay anyone who promises "guaranteed reinstatement in 24 hours".** Nobody outside Google can guarantee that, and some of these services use tricks that lead to permanent removal.

Instead, take a breath and fix the cause first.

## Step 2: Fix your profile so it follows the guidelines

Read Google''s "Guidelines for representing your business on Google" once, slowly. Then correct anything that does not follow them **before** you appeal:

- **Business name:** exactly as it appears on your signboard and registration. Remove city names, services and slogans.
- **Address:** a real, staffed location with your signage, or hide the address and use service areas.
- **Category:** the most specific primary category that describes your main business, like "Dental clinic" rather than "Doctor".
- **Phone number:** a local number that you answer, matching your website.
- **Website:** links to your own site, which shows the same name, address and phone number. If you do not have one, our [business website design checklist](/blog/business-website-design-checklist) explains what a small business site needs.
- **Duplicates:** if you have more than one profile for the same location, note them – you can mention them in the appeal.

If your profile is suspended and you cannot edit it, write down the corrections you would make. Google lets you explain them in the appeal.

## Step 3: Collect the right proof

A successful appeal is mostly about evidence. Google''s reviewers need to see that the business is real, exists at that address and uses that name. Collect clear, readable files (photos or PDFs):

| Proof | What it shows |
|---|---|
| Photos of the storefront with your permanent signboard, plus the street or nearby landmark | You operate at this address under this name |
| Photos inside the premises – reception, counter, work area, equipment | It is a real, working business |
| GST certificate, Udyam registration, shop and establishment licence or trade licence | Legal business name and address |
| Utility bill or rent agreement for the premises in the business name | You occupy the address |
| Professional registration (for doctors, lawyers, CAs and similar) | You are licensed for that work |
| Branded vehicle, uniforms or tools (for service-area businesses) | You serve customers in that area |

Make sure the **business name and address on these documents match the profile exactly**. A mismatch is one of the main reasons appeals fail. Photos should be original and recent – not stock images or edited pictures.

## Step 4: Submit the appeal through the official tool

Google handles suspensions through the **Business Profile appeals tool** in its Business Profile Help centre. Sign in with the Google account that owns the profile, select the suspended profile and follow the steps to upload your evidence.

Keep your explanation short, polite and factual. For example:

"Our clinic has operated at this address since 2019 under the name Sharma Dental Clinic, as shown on our signboard and shop licence. We have corrected the business name to remove extra words and confirmed the address is staffed during business hours. Attached: storefront photos, shop licence and electricity bill."

Some appeals also ask for **video verification** – a short, continuous video showing the signboard, the surroundings and the inside of the business, or proof of a service-area business such as tools and a branded vehicle. Record it in one take, in daylight, without cuts.

## Step 5: Wait – and check the status in the same tool

Appeals usually take from a few days to a few weeks. You can see the status (in review, approved or rejected) in the appeals tool. Submitting the same appeal repeatedly does not speed things up.

- **If approved:** your profile and reviews usually come back as they were. Check every detail, and avoid big changes for a few weeks.
- **If rejected:** read the message carefully. Fix what is still wrong, collect stronger proof (especially clear signage and a document in the exact business name) and appeal again. If the decision is final, you can ask for help in the Google Business Profile Community forum, where volunteer Product Experts can sometimes escalate genuine cases.

