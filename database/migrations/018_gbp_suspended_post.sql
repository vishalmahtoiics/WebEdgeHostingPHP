## How to avoid another suspension

- Keep the business name exactly as on your signboard – no keywords, ever.
- Make one change at a time, and only when something has really changed.
- Never buy reviews or offer anything in return for them. Ask happy customers honestly, with a direct review link.
- Keep the same name, address and phone number on your website, profile and social pages.
- Add at least two trusted people as managers, and remove old agencies or employees when they leave.
- Post updates and photos regularly – an active, genuine profile looks trustworthy.

## Frequently asked questions

### Why was my Google Business Profile suspended without warning?

Google''s systems often suspend profiles automatically after a risky edit or when something looks against the guidelines, such as extra words in the name, an ineligible address or a duplicate listing. They rarely give the exact reason, so check your profile against the guidelines and fix any problem before appealing.

### How long does it take to reinstate a suspended Google Business Profile?

Most appeals are reviewed within a few days to a few weeks. Clear evidence that matches your profile exactly, such as signboard photos and a licence in the same business name, gives the best chance of a quick approval.

### Will I lose my reviews if my business profile is suspended?

Reviews are usually hidden while the profile is suspended or removed, and normally come back when the profile is reinstated. Creating a new profile instead does not carry your old reviews across.

### Can I create a new Google Business Profile instead of appealing?

It is not recommended. Google can link the new profile to the suspended one and suspend it too, which makes recovery harder. Appeal the original profile with proper evidence.

### Can a home-based business have a Google Business Profile?

Yes, if you meet customers in person. If customers visit your home office, you can show the address. If you go to customers, set it up as a service-area business and hide your home address.

